/**
 * build.mjs — generates the Cloudflare static site (cloudflare/dist) from the SAME
 * source partials used by the Apps Script website (src/*.html). There is one copy of
 * the UI code; this script only re-packages it:
 *   - <style> blocks  → hashed .css files
 *   - <script> blocks → hashed .js bundles (no inline scripts → strict CSP possible)
 *   - google.script.* → web/platform.js adapter (same-origin /api/* calls)
 *
 *   node cloudflare/build.mjs
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync, copyFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, '..', 'src');
const WEB = join(here, 'web');
const DIST = join(here, 'dist');

const read = (p) => readFileSync(p, 'utf8');
const partial = (name) => read(join(SRC, name + '.html'));

function extract(name, tag) {
  const m = new RegExp('<' + tag + '>([\\s\\S]*?)</' + tag + '>').exec(partial(name));
  if (!m) throw new Error(`No <${tag}> block in ${name}.html`);
  return m[1];
}
function links(name) {
  return (partial(name).match(/<link[^>]*>/g) || []).join('\n  ');
}
function hashed(dir, base, ext, content) {
  const h = createHash('sha256').update(content).digest('hex').slice(0, 10);
  const file = `${base}.${h}.${ext}`;
  writeFileSync(join(dir, file), content);
  return '/assets/' + file;
}

// Site-wide configuration injected at the top of each bundle (public values only).
const configPublic = `window.__APP_URL__ = ''; window.__ADMIN_URL__ = '/admin'; window.__PLATFORM__ = 'cloudflare';\n`;
const configAdmin = `window.__APP_URL__ = '/'; window.__ADMIN_URL__ = '/admin'; window.__AUTH_MODE__ = 'cookie'; window.__SITE_NAME__ = 'UniMAP Resources Hub'; window.__PLATFORM__ = 'cloudflare';\n`;

const banner = '/* UniMAP Resources Hub — generated by cloudflare/build.mjs from src/*.html. Do not edit here. */\n';

rmSync(DIST, { recursive: true, force: true });
mkdirSync(join(DIST, 'assets'), { recursive: true });

const siteCss = hashed(join(DIST, 'assets'), 'site', 'css', banner + extract('Styles', 'style'));
const adminCss = hashed(join(DIST, 'assets'), 'admin', 'css', banner + extract('AdminStyles', 'style'));
const themeJs = hashed(join(DIST, 'assets'), 'theme', 'js', read(join(WEB, 'theme.js')));

const publicJs = hashed(join(DIST, 'assets'), 'public', 'js', banner + [
  configPublic,
  read(join(WEB, 'platform.js')),
  read(join(WEB, 'analytics.js')),
  extract('Ui', 'script'),
  extract('I18n', 'script'),
  extract('PublicApp', 'script'),
  extract('PublicSubmit', 'script'),
  read(join(WEB, 'boot-public.js'))
].join('\n;\n'));

const adminJs = hashed(join(DIST, 'assets'), 'admin', 'js', banner + [
  configAdmin,
  read(join(WEB, 'platform.js')),
  extract('Ui', 'script'),
  extract('AdminApp', 'script'),
  extract('AdminViews', 'script'),
  extract('AdminForms', 'script'),
  read(join(WEB, 'boot-admin.js'))
].join('\n;\n'));

const head = (title, extra) => `<!DOCTYPE html>
<html lang="en" dir="ltr">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <title>${title}</title>
  <meta name="description" content="An independent student initiative that organises academic resources shared by UniMAP students. By Students, For Students. Not an official UniMAP system.">
  <meta name="theme-color" content="#f7f7f5">
  <link rel="icon" href="/favicon.svg" type="image/svg+xml">
  ${extra || ''}
  <script src="${themeJs}"></script>
  ${links('Styles')}
  <link rel="stylesheet" href="${siteCss}">`;

const skeleton = `<div class="container" style="padding-block:96px">
      <div class="skeleton" style="height:28px;width:180px"></div>
      <div class="skeleton" style="height:56px;max-width:560px;margin-top:20px"></div>
      <div class="skeleton" style="height:20px;max-width:640px;margin-top:20px"></div>
      <div class="skeleton" style="height:52px;max-width:720px;margin-top:36px;border-radius:999px"></div>
    </div>`;

writeFileSync(join(DIST, 'index.html'), `${head('UniMAP Resources Hub')}
</head>
<body>
  <a class="sr-only" href="#main">Skip to content</a>
  <div id="app">
    ${skeleton}
  </div>
  <div id="toasts" class="toasts" aria-live="polite"></div>
  <noscript><p style="padding:24px">UniMAP Resources Hub needs JavaScript to run.</p></noscript>
  <script src="${publicJs}" defer></script>
</body>
</html>
`);

writeFileSync(join(DIST, 'admin.html'), `${head('Admin — UniMAP Resources Hub', '<meta name="robots" content="noindex, nofollow">')}
  <link rel="stylesheet" href="${adminCss}">
</head>
<body class="admin">
  <div id="app">
    <div class="auth-wrap"><div class="spinner" aria-label="Loading" style="width:28px;height:28px;color:var(--text-3)"></div></div>
  </div>
  <div id="toasts" class="toasts" aria-live="polite"></div>
  <script src="${adminJs}" defer></script>
</body>
</html>
`);

writeFileSync(join(DIST, '404.html'), `${head('Page not found — UniMAP Resources Hub')}
</head>
<body>
  <main class="container" style="padding-block:96px"><div class="card empty">
    <h3>Page not found</h3><p>This page does not exist.</p>
    <a class="btn btn-primary" href="/">Back to UniMAP Resources Hub</a></div></main>
</body>
</html>
`);

for (const f of ['favicon.svg', 'robots.txt', '_headers']) copyFileSync(join(WEB, f), join(DIST, f));
console.log('Built cloudflare/dist:', { siteCss, adminCss, publicJs, adminJs });
